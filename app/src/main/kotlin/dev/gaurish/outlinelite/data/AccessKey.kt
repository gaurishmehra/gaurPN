package dev.gaurish.outlinelite.data

import org.json.JSONObject
import java.net.URLDecoder
import java.net.URLEncoder

data class AccessKey(
    val name: String,
    val host: String,
    val port: Int,
    val method: String,
    val password: String,
) {
    /** Stable identity for DataStore keys and active selection. */
    val id: String get() = "$host:$port|$method|${password.hashCode()}"

    /** Backing config for outlinev.ConnectTunnel / CheckConnectivity. */
    fun configJson(): String = JSONObject().apply {
        put("host", host)
        put("port", port)
        put("method", method)
        put("password", password)
    }.toString()

    fun displayAddress(): String = "$host:$port"

    /** Exports the key as an ss:// URI (standard Outline format). */
    fun toSsUri(): String {
        val rawUserinfo = "$method:$password"
        val b64 = SsKeyParser.base64UrlEncode(rawUserinfo.toByteArray(Charsets.UTF_8))
        val hostPart = if (host.contains(':') && !host.startsWith('[')) "[$host]" else host
        val encodedName = runCatching { URLEncoder.encode(name, "UTF-8").replace("+", "%20") }.getOrDefault(name)
        return "ss://$b64@$hostPart:$port#$encodedName"
    }
}

/**
 * Parses Outline access keys (`ss://` URIs).
 *
 * Handles the common shapes generated by Outline Manager and key-sharing sites:
 *  - `ss://BASE64URL(method:password)@host:port#name`  (current Outline format)
 *  - `ss://method%3Apassword@host:port#name`           (plaintext URL-encoded)
 *  - `ss://BASE64URL(method:password@host:port)#name`  (legacy whole-body format)
 *
 * Pure Kotlin so it can run in JVM unit tests.
 */
object SsKeyParser {

    private const val URL_ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"
    private const val STD_ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"

    private val URL_MAP = IntArray(128) { -1 }.apply {
        for (i in URL_ALPHABET.indices) this[URL_ALPHABET[i].code] = i
    }
    private val STD_MAP = IntArray(128) { -1 }.apply {
        for (i in STD_ALPHABET.indices) this[STD_ALPHABET[i].code] = i
    }

    fun parse(rawInput: String): AccessKey? = runCatching {
        val raw = rawInput.trim()
        if (!raw.startsWith("ss://", ignoreCase = true)) return@runCatching null
        var rest = raw.substring(5)

        var name = ""
        val frag = rest.indexOf('#')
        if (frag >= 0) {
            name = urlDecode(rest.substring(frag + 1))
            rest = rest.substring(0, frag)
        }
        val qm = rest.indexOf('?')
        if (qm >= 0) {
            val query = rest.substring(qm + 1)
            if (query.contains("plugin=")) return@runCatching null // SIP002 plugins unsupported
            rest = rest.substring(0, qm)
        }

        val at = rest.indexOf('@')
        val (method: String, password: String, hostport: String) = if (at > 0) {
            val userinfo = rest.substring(0, at)
            val hostport = rest.substring(at + 1)
            val pair = decodeUserinfo(userinfo) ?: return@runCatching null
            Triple(pair.first, pair.second, hostport)
        } else {
            // Legacy: whole body is BASE64 of "method:password@host:port"
            val decoded = base64Decode(rest, urlSafe = true)
                ?: base64Decode(rest, urlSafe = false)
                ?: return@runCatching null
            val s = String(decoded, Charsets.UTF_8)
            val innerAt = s.indexOf('@')
            if (innerAt <= 0) return@runCatching null
            val pair = decodeUserinfo(s.substring(0, innerAt)) ?: return@runCatching null
            Triple(pair.first, pair.second, s.substring(innerAt + 1))
        }

        val (host, port) = parseHostPort(hostport) ?: return@runCatching null
        AccessKey(
            name = name.ifBlank { "$host:$port" },
            host = host,
            port = port,
            method = method,
            password = password,
        )
    }.getOrNull()

    /** Accepts `method:password`, percent-encoded within the URL, or base64 of that. */
    private fun decodeUserinfo(userinfo: String): Pair<String, String>? {
        // Percent-encoded or raw plaintext: "method:password" — password may itself contain ':'.
        if (userinfo.contains('%') || userinfo.contains(':')) {
            val s = if (userinfo.contains('%')) urlDecode(userinfo) else userinfo
            val idx = s.indexOf(':')
            if (idx < 0) return null
            return s.substring(0, idx) to s.substring(idx + 1)
        }
        val decoded = base64Decode(userinfo, urlSafe = true)
            ?: base64Decode(userinfo, urlSafe = false)
            ?: return null
        val s = String(decoded, Charsets.UTF_8)
        val idx = s.indexOf(':')
        if (idx < 0) return null
        return s.substring(0, idx) to s.substring(idx + 1)
    }

    private fun urlDecode(s: String): String =
        runCatching { URLDecoder.decode(s, "UTF-8") }.getOrDefault(s)

    internal fun parseHostPort(href: String): Pair<String, Int>? {
        val parsed = parseHostPortRaw(href) ?: return null
        return if (parsed.second in 1..65535) parsed else null
    }

    private fun parseHostPortRaw(href: String): Pair<String, Int>? {
        val open = href.indexOf('[')
        if (open >= 0) {
            val close = href.indexOf(']') + 1
            val host = href.substring(open + 1, close - 1)
            val portStr = href.substring(close + 1).removePrefix(":")
            return portStr.toIntOrNull()?.let { host to it }
        }
        val idx = href.lastIndexOf(':')
        if (idx <= 0) return null
        val port = href.substring(idx + 1).toIntOrNull() ?: return null
        return href.substring(0, idx) to port
    }

    fun base64UrlEncode(bytes: ByteArray): String {
        val sb = StringBuilder()
        var bitBuf = 0
        var bitCount = 0
        for (b in bytes) {
            bitBuf = (bitBuf shl 8) or (b.toInt() and 0xFF)
            bitCount += 8
            while (bitCount >= 6) {
                bitCount -= 6
                sb.append(URL_ALPHABET[(bitBuf shr bitCount) and 0x3F])
            }
        }
        if (bitCount > 0) {
            sb.append(URL_ALPHABET[(bitBuf shl (6 - bitCount)) and 0x3F])
        }
        return sb.toString()
    }

    private fun base64Decode(input: String, urlSafe: Boolean): ByteArray? {
        val map = if (urlSafe) URL_MAP else STD_MAP
        if (input.isEmpty()) return null
        val clean = input.trim().replace("=", "")
        var bitBuf = 0L
        var bitCount = 0
        val out = ArrayList<Byte>(clean.length * 6 / 8 + 1)
        for (c in clean) {
            val code = c.code
            val v = if (code in 0..127) map[code] else -1
            if (v < 0) return null
            bitBuf = (bitBuf shl 6) or v.toLong()
            bitCount += 6
            if (bitCount >= 8) {
                bitCount -= 8
                out.add(((bitBuf shr bitCount) and 0xFFL).toInt().toByte())
            }
        }
        return out.toByteArray()
    }
}
